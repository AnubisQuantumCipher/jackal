class ProgrammingBlankingIsLoadBearingTest(ProgrammingPackCase):
    """Attribute each poison refusal to the guard that actually causes it.

    "The checker refuses this" is not the same claim as "this specific guard
    refuses this". These tests disable one guard at a time on a private import of
    the checker -- the file on disk is never touched -- and record which phantoms
    become visible. Anything that stays invisible is refused by something else,
    and that is said rather than glossed.
    """

    def _unguarded_checker(self, *, blanking: bool, python_ast: bool):
        checker = GEN._load_module("probe_test_exists_verify", GEN.TEST_EXISTS_CHECKER)
        if not blanking:
            checker._blank_noncode = lambda text: text
        if not python_ast:
            checker._python_declarations = lambda text, symbol: None
        return checker

    def test_instrument_comment_and_string_blanking_is_load_bearing(self) -> None:
        # With the blanking pass disabled (and, for Python, the exact `ast` path
        # disabled too), these phantoms ARE found -- so the refusals recorded for
        # them are caused by those guards and not by an unrelated accident.
        probe = self._unguarded_checker(blanking=False, python_ast=False)
        for fixture, symbol in (
            (DOCSTRING_FIXTURE, "corpus_docstring_phantom"),
            (RAW_STRING_FIXTURE, "corpus_raw_string_phantom"),
            (BLOCK_COMMENT_FIXTURE, "corpus_block_comment_phantom"),
        ):
            with self.subTest(fixture=fixture):
                text = (ROOT / fixture).read_text(encoding="utf-8")
                unguarded = probe.find_declarations(
                    text, symbol, suffix=Path(fixture).suffix
                )
                self.assertNotEqual(
                    unguarded, [], "the fixture is not a trap for this guard at all"
                )
                self.assertEqual(GEN.declarations(fixture, symbol), [])

    def test_instrument_line_comment_phantom_is_refused_by_the_line_anchor(self) -> None:
        """Honest attribution: this one is NOT the blanking pass.

        A `// pub fn ...` line still starts with `//` after blanking is disabled,
        and every declaration pattern is anchored with `^\\s*`, so the pattern
        never matches. Claiming the blanking pass catches it would have been an
        overstatement, and the probe above is what showed the difference.
        """
        probe = self._unguarded_checker(blanking=False, python_ast=True)
        text = (ROOT / LINE_COMMENT_FIXTURE).read_text(encoding="utf-8")
        self.assertEqual(
            probe.find_declarations(text, "corpus_line_comment_phantom", suffix=".rs"), []
        )
        self.assertEqual(
            GEN.declarations(LINE_COMMENT_FIXTURE, "corpus_line_comment_phantom"), []
        )

    def test_instrument_python_ast_path_supersedes_the_regex_path(self) -> None:
        # The docstring phantom is refused twice over: the `ast` path never sees
        # it, and the blanking pass would remove it anyway. Disabling only `ast`
        # must still refuse, which is what defence in depth means here.
        probe = self._unguarded_checker(blanking=True, python_ast=False)
        text = (ROOT / DOCSTRING_FIXTURE).read_text(encoding="utf-8")
        self.assertEqual(
            probe.find_declarations(text, "corpus_docstring_phantom", suffix=".py"), []
        )
        # Control: the same unguarded checker still finds the real declaration.
        self.assertNotEqual(
            probe.find_declarations(text, "corpus_docstring_anchor", suffix=".py"), []
        )


class ProgrammingSymlinkRefusalTest(ProgrammingPackCase):
    """Path-safety refusals, which need a tree the repository must not contain.

    Symlinks are built in a temporary root and the checker is pointed at it with
    `--root`. The engine still mints the certificate -- it never reads the file --
    so these cases exercise the checker's own path guards.
    """

    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory(prefix="jackal-programming-symlink-")
        self.root = Path(self.temp.name)
        self.real = self.root / "genuine.py"
        self.real.write_text(
            "def symlink_probe_target(value):\n    return value\n", encoding="utf-8"
        )
        self.addCleanup(self.temp.cleanup)

    def _mint(self, file_path: str, sha: str, symbol: str, line: str, count: str):
        observed = self.engine.run("test-exists", file_path, sha, symbol, line, count)
        self.assertEqual(observed.returncode, 0, observed.stderr[-800:])
        return observed.certificate(GEN.TEST_EXISTS_PREFIX)

    def _sha(self, path: Path) -> str:
        return hashlib.sha256(path.read_bytes()).hexdigest()

    def test_control_temporary_root_accepts_the_real_file(self) -> None:
        # Non-vacuity control for this class: with no symlink in the way the very
        # same temp root and the very same checker ACCEPT.
        certificate = self._mint(
            "genuine.py", self._sha(self.real), "symlink_probe_target", "1", "1"
        )
        verdict = GEN.check_test_exists(certificate, root=self.root)
        self.assertEqual(verdict.summary, "ACCEPT", verdict.line)

    def test_poison_file_path_names_a_symlink(self) -> None:
        (self.root / "linked.py").symlink_to(self.real)
        certificate = self._mint(
            "linked.py", self._sha(self.real), "symlink_probe_target", "1", "1"
        )
        verdict = GEN.check_test_exists(certificate, root=self.root)
        self.assertEqual(verdict.reason_class, "cert-path-symlink", verdict.line)
        self.assertEqual(verdict.returncode, 2)

    def test_poison_symlinked_directory_on_the_path(self) -> None:
        real_dir = self.root / "real_pkg"
        real_dir.mkdir()
        target = real_dir / "genuine.py"
        target.write_text(
            "def symlink_probe_target(value):\n    return value\n", encoding="utf-8"
        )
        (self.root / "linked_pkg").symlink_to(real_dir, target_is_directory=True)
        certificate = self._mint(
            "linked_pkg/genuine.py", self._sha(target), "symlink_probe_target", "1", "1"
        )
        verdict = GEN.check_test_exists(certificate, root=self.root)
        self.assertEqual(verdict.reason_class, "cert-path-symlink", verdict.line)
        self.assertIn("linked_pkg", verdict.line)


class ProgrammingHandBuiltCertificateTest(ProgrammingPackCase):
    """Checker guards that the engine's own form checks make unreachable.

    These certificates cannot be produced by the pinned engine, so they are built
    directly. That is stated rather than hidden: the point is that the checker
    does not rely on the engine having already refused.
    """

    def _check(self, claim: dict, kind: str = "test-exists"):
        envelope = {
            "claim": claim,
            "kind": kind,
            "schema": "jackal-test-exists-cert-v1",
            "witness": {},
        }
        payload = GEN.TEST_EXISTS_PREFIX + json.dumps(
            envelope, sort_keys=True, separators=(",", ":")
        )
        return GEN.check_test_exists(payload)

    def test_hand_built_zero_count_certificate_is_an_absence(self) -> None:
        verdict = self._check(
            {
                "declaration_count": "0",
                "declaration_line": "1",
                "file_path": PY_FIXTURE,
                "file_sha256": GEN.sha256_file(PY_FIXTURE),
                "symbol": "corpus_python_target",
            }
        )
        self.assertEqual(verdict.reason_class, "cert-absence-as-existence", verdict.line)

