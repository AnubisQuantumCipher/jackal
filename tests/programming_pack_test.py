class ProgrammingCorpusReplayTest(ProgrammingPackCase):
    """Replay every frozen case, including any not named individually above."""

    def test_every_frozen_case_replays_identically(self) -> None:
        for case_id in sorted(self.rows):
            with self.subTest(case=case_id):
                self.replay(case_id)

    def test_every_frozen_case_is_named_by_an_individual_test(self) -> None:
        """Guard against a corpus row that only the bulk replay ever touches.

        A case reachable solely through the loop above is easy to lose track of;
        requiring each `case_id` to appear in some test method's source keeps the
        individual gates and the corpus in step.
        """
        source = Path(__file__).read_text(encoding="utf-8")
        unnamed = [
            case_id
            for case_id in sorted(self.rows)
            if f'"{case_id}"' not in source
        ]
        self.assertEqual(unnamed, [])


class ProgrammingCaseCensusTest(ProgrammingPackCase):
    def test_case_census(self) -> None:
        positive = [n for n in dir(ProgrammingPositiveTest) if n.startswith("test_positive_")]
        refusal = [n for n in dir(ProgrammingEngineRefusalTest) if n.startswith("test_refusal_")]
        poison = [
            n for n in dir(ProgrammingCheckerRefusalTest) if n.startswith("test_poison_")
        ] + [n for n in dir(ProgrammingSymlinkRefusalTest) if n.startswith("test_poison_")]
        control = [
            n
            for n in dir(ProgrammingPositiveTest)
            + dir(ProgrammingSymlinkRefusalTest)
            + dir(ProgrammingHandBuiltCertificateTest)
            if n.startswith("test_control_") or "control" in n
        ]
        instrument = [
            n for n in dir(ProgrammingBlankingIsLoadBearingTest) if n.startswith("test_instrument_")
        ] + [n for n in dir(ProgrammingHarnessTest) if n.startswith("test_")]
        print(
            f"\nprogramming_case_census positive={len(positive)} "
            f"engine_refusal={len(refusal)} checker_refusal={len(poison)} "
            f"control={len(control)} instrument={len(instrument)} "
            f"corpus_cases={len(self.rows)} "
            f"corpus_counts={self.corpus['case_counts']}",
            file=sys.stderr,
        )
        self.assertGreaterEqual(len(positive), 5)
        self.assertGreaterEqual(len(refusal), 9)
        self.assertGreaterEqual(len(poison), 12)
        self.assertGreaterEqual(len(control), 3)
        self.assertGreaterEqual(len(instrument), 8)


