class ProgrammingRouteParityTest(ProgrammingPackCase):
    """A pack route must preserve the direct command's stdout bytes exactly."""

    def _assert_parity(self, case_id: str, operation_id: str) -> None:
        row = self.row(case_id)
        argv = list(row["argv"])
        direct = self.engine.run(row["engine_command"], *argv)
        routed = self.engine.route(self.corpus["pack_id"], operation_id, *argv)
        self.assertEqual(direct.returncode, 0, direct.stderr[-800:])
        self.assertEqual(routed.returncode, 0, routed.stderr[-800:])
        self.assertEqual(routed.stdout, direct.stdout)
        # Byte parity would also hold if both sides emitted nothing, so pin the
        # payload the parity is about.
        self.assertIn(GEN.TEST_EXISTS_PREFIX, routed.stdout)
        self.assertTrue(row["route_parity"])

    def test_route_parity_test_exists(self) -> None:
        self._assert_parity(
            "positive_test_exists_single_declaration", GEN.OP_TEST_EXISTS
        )

    def test_route_parity_claim_cites_test(self) -> None:
        self._assert_parity(
            "positive_claim_cites_test_citation_resolves", GEN.OP_CLAIM_CITES
        )

    def test_route_parity_holds_for_every_certificate_bearing_case(self) -> None:
        for case_id, row in sorted(self.rows.items()):
            if row["checker"] is None:
                continue
            with self.subTest(case=case_id):
                self.assertIs(row["route_parity"], True)


