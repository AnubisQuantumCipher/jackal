#!/usr/bin/env python3
"""Engine-level gates for the `jackal.programming.source` domain pack.

Every case here drives the pinned Anubis engine as a subprocess and, where the
engine emits a certificate, the real independent checker
(`tools/test_exists_verify.py`) as a second subprocess. Nothing is stubbed and
no expected value is written by hand: declaration line numbers and counts are
derived by calling the checker's own `find_declarations`, and every refusal
class is read out of the process output.

Case data comes from the frozen corpus at `tests/corpus/programming_corpus_v1.json`
so that the expectations are observations of a recorded run rather than
assertions invented here. The corpus is regenerated by
`tests/corpus/generate_pack_corpus.py --freeze` and audited by `--self-check`.

The boundary these gates defend
-------------------------------
`test-exists` is byte-exact about a structural fact, so its assurance ceiling is
`exact` -- and a test existing is never evidence that the code under test is
correct, so its consequence ceiling stops at `informational`. The engine
validates only canonical *form*; every claim about the bytes on disk is
established by the checker or not at all. The `poison` cases below are the
interesting half: each one is a well-formed certificate the engine happily mints
and the checker refuses.

What these gates do NOT establish
---------------------------------
That a symbol the checker finds is a test, that it runs, that it asserts
anything, or that it covers whatever a surrounding document claims. Those are
permanent nonclaims of the pack, not gaps in this file.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _load_generator():
    path = ROOT / "tests" / "corpus" / "generate_pack_corpus.py"
    spec = importlib.util.spec_from_file_location("jackal_pack_corpus", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GEN = _load_generator()

PY_FIXTURE = GEN.PY_FIXTURE
DOCSTRING_FIXTURE = GEN.DOCSTRING_FIXTURE
RAW_STRING_FIXTURE = GEN.RAW_STRING_FIXTURE
LINE_COMMENT_FIXTURE = GEN.LINE_COMMENT_FIXTURE
BLOCK_COMMENT_FIXTURE = GEN.BLOCK_COMMENT_FIXTURE
CLAIM_DOC = GEN.CLAIM_DOC


class ProgrammingPackCase(unittest.TestCase):
    """Shared harness: one engine build for the whole module, plus replay."""

    CORPUS = "programming"

    @classmethod
    def setUpClass(cls) -> None:
        if not GEN.ANUBIS.is_file():
            raise unittest.SkipTest(f"pinned Anubis compiler unavailable at {GEN.ANUBIS}")
        cls.engine = GEN.Engine.shared()
        cls.corpus = GEN.load_corpus(cls.CORPUS)
        cls.rows = GEN.cases_by_id(cls.corpus)

    def row(self, case_id: str) -> dict:
        self.assertIn(case_id, self.rows, f"{case_id} is not in the frozen corpus")
        return self.rows[case_id]

    def replay(self, case_id: str):
        """Re-run one frozen case live and assert it still behaves identically.

        Returns `(observation, verdict)`; `verdict` is None for engine refusals,
        which emit no certificate to check.
        """
        row = self.row(case_id)
        argv = list(row["argv"])
        if row["invocation"] == "pack-route":
            observed = self.engine.route(
                row.get("route_pack_id", self.corpus["pack_id"]),
                row.get("route_operation_id", row["operation_id"]),
                *argv,
            )
        else:
            observed = self.engine.run(row["engine_command"], *argv)

        self.assertEqual(observed.returncode, row["engine"]["returncode"])
        self.assertEqual(observed.refusal_class, row["engine"]["refusal_class"])
        self.assertEqual(observed.stdout, row["engine"]["stdout"])

        if row["checker"] is None:
            return observed, None

        certificate = observed.certificate(GEN.TEST_EXISTS_PREFIX)
        if "tamper" in row:
            certificate = GEN.apply_tamper(certificate, GEN.TEST_EXISTS_PREFIX, row["tamper"])
        self.assertEqual(certificate, row["certificate"])
        verdict = GEN.check_test_exists(certificate)
        self.assertEqual(verdict.summary, row["checker"]["verdict"], verdict.line)
        self.assertEqual(verdict.returncode, row["checker"]["returncode"])
        return observed, verdict

    def assertEngineRefusal(self, case_id: str, expected: str) -> None:
        observed, verdict = self.replay(case_id)
        self.assertNotEqual(observed.returncode, 0)
        self.assertEqual(observed.refusal_class, expected)
        self.assertIsNone(verdict)
        # No certificate may leak out of a refusal, or a caller could scrape a
        # partial line out of the transcript and check it in isolation.
        self.assertNotIn(GEN.TEST_EXISTS_PREFIX, observed.stdout)

    def assertCheckerRefusal(self, case_id: str, expected: str) -> None:
        observed, verdict = self.replay(case_id)
        self.assertEqual(observed.returncode, 0, "the engine must mint this certificate")
        self.assertIsNotNone(verdict)
        assert verdict is not None
        self.assertEqual(verdict.reason_class, expected, verdict.line)
        self.assertEqual(verdict.returncode, 2)


class ProgrammingHarnessTest(ProgrammingPackCase):
    """Validate the instrument before trusting any number it produces."""

    def test_harness_drives_the_pinned_compiler(self) -> None:
        self.assertEqual(self.engine.anubis_pin, GEN.ANUBIS.name)
        self.assertEqual(
            self.engine.engine_source_sha256,
            hashlib.sha256((ROOT / "jackal_calc.anb").read_bytes()).hexdigest(),
        )
        self.assertIn(self.engine.mode, ("prebuilt-native", "launcher-per-call"))
        self.assertIn("exact-cert=", self.engine.probe_stdout)

    def test_fast_path_is_byte_identical_to_the_jackal_launcher(self) -> None:
        """The whole suite rests on this: the fast path is the same engine.

        `Engine.__init__` already proves it for the build probe. This repeats the
        proof for a `test-exists` invocation through the real `./jackal` script,
        which recompiles from `jackal_calc.anb` via `anubis run`, so the parity
        claim is not confined to one command.
        """
        if self.engine.mode != "prebuilt-native":
            self.skipTest("harness is already using the launcher for every call")
        argv = list(self.row("positive_test_exists_single_declaration")["argv"])
        fast = self.engine.run("test-exists", *argv)
        launched = self.engine.run_via_launcher("test-exists", *argv)
        self.assertEqual(launched.returncode, 0, launched.stderr[-800:])
        self.assertEqual(launched.stdout, fast.stdout)

    def test_corpus_fixture_digests_still_match_disk(self) -> None:
        for entry in self.corpus["fixtures"]:
            with self.subTest(fixture=entry["path"]):
                self.assertEqual(GEN.sha256_file(entry["path"]), entry["sha256"])

    def test_corpus_checker_identity_still_matches_disk(self) -> None:
        self.assertEqual(
            GEN.sha256_file(self.corpus["checker"]["path"]),
            self.corpus["checker"]["sha256"],
        )

    def test_corpus_aggregate_digest_is_self_consistent(self) -> None:
        recomputed = GEN.corpus_digest(self.corpus)
        self.assertEqual(self.corpus[GEN.DIGEST_KEY], recomputed)

    def test_corpus_covers_all_three_case_classes(self) -> None:
        counts = self.corpus["case_counts"]
        self.assertGreaterEqual(counts["positive"], 6)
        self.assertGreaterEqual(counts["refusal"], 9)
        self.assertGreaterEqual(counts["poison"], 8)


